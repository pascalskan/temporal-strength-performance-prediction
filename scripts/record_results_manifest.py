"""
Record a checksummed index of the results a run produced.

`results/` is excluded from version control -- the prediction files alone run to
hundreds of megabytes -- so nothing connected the repository to the figures
quoted in the README. A reader could not tell whether their rerun reproduced
the published numbers without regenerating five and a half hours of output and
comparing by eye.

This writes two committed artefacts:

  docs/results_manifest.json   every result file, with size and SHA-256
  docs/results_summary.md      the headline tables, in the README's own terms

Together they let a reader verify a rerun file by file, and read the reported
numbers without running anything.

    python scripts/record_results_manifest.py
    python scripts/record_results_manifest.py --verify
"""
import argparse
import json
import sys
from datetime import datetime, UTC
from pathlib import Path

import pandas as pd

from src.core.logging import get_logger
from src.data.provenance import MANIFEST_FILENAME, compute_file_digest, load_manifest
from src.io.paths import ProjectPaths

logger = get_logger(__name__)

MANIFEST_PATH = Path("docs/results_manifest.json")
SUMMARY_PATH = Path("docs/results_summary.md")

# Prediction-level files are large and are regenerated rather than inspected;
# their digests are recorded but they are not summarised.
SUMMARISE = {
    "walk_forward/walk_forward_summary.csv": "Walk-forward, pooled over all predictions",
    "walk_forward/matched_subset/matched_subset_summary.csv":
        "Walk-forward, restricted to observations every model scored",
    "walk_forward/walk_forward_comparison.csv": "Paired cluster bootstrap comparisons",
    "forward/metrics.csv": "Forward protocol",
    "forward/metrics_retro.csv": "Retrospective reference, same models and features",
    "evaluation/model_comparison_full.csv": "Retrospective, standalone pipeline (tuned)",
    "traditional/traditional_metrics.csv": "Traditional equations, retrospective",
    "ablation/ablation_summary.csv": "Feature ablation",
}


def index_results(results_root: Path) -> list:
    entries = []
    for path in sorted(results_root.rglob("*")):
        if not path.is_file():
            continue
        entries.append({
            "path": path.relative_to(results_root).as_posix(),
            "size_bytes": path.stat().st_size,
            "sha256": compute_file_digest(path),
        })
    return entries


def build_manifest(results_root: Path) -> dict:
    dataset = load_manifest(ProjectPaths.data_dir() / MANIFEST_FILENAME) or {}
    entries = index_results(results_root)

    return {
        "recorded_at": datetime.now(UTC).isoformat(),
        # Ties results to the data that produced them, so a mismatch can be
        # attributed to the snapshot rather than to the code.
        "dataset_sha256": dataset.get("sha256"),
        "dataset_rows": dataset.get("content", {}).get("rows"),
        "file_count": len(entries),
        "total_bytes": sum(e["size_bytes"] for e in entries),
        "files": entries,
    }


def render_markdown_table(frame: pd.DataFrame) -> list:
    """
    Render a frame as a Markdown table.

    Hand-rolled rather than using DataFrame.to_markdown, which requires
    tabulate. Adding a pinned dependency purely to format a document is not
    worth the reproducibility surface it adds.
    """
    def cell(value):
        if isinstance(value, float):
            return f"{value:.4f}"
        return str(value)

    headers = [str(c) for c in frame.columns]
    rows = [[cell(v) for v in record] for record in frame.itertuples(index=False)]

    widths = [
        max(len(headers[i]), *(len(r[i]) for r in rows)) if rows else len(headers[i])
        for i in range(len(headers))
    ]

    def line(values):
        return "| " + " | ".join(v.ljust(widths[i]) for i, v in enumerate(values)) + " |"

    return [
        line(headers),
        "|" + "|".join("-" * (w + 2) for w in widths) + "|",
        *(line(r) for r in rows),
    ]


def render_summary(results_root: Path) -> str:
    lines = [
        "# Results Summary",
        "",
        "Generated by `scripts/record_results_manifest.py`. Committed so the",
        "reported figures can be read, and a rerun checked, without regenerating",
        "the full output tree.",
        "",
    ]

    dataset = load_manifest(ProjectPaths.data_dir() / MANIFEST_FILENAME) or {}
    if dataset:
        content = dataset.get("content", {})
        lines += [
            f"Dataset snapshot `{dataset.get('sha256', '?')[:16]}...` -- "
            f"{content.get('rows', 0):,} records, "
            f"{content.get('earliest_record')} to {content.get('latest_record')}.",
            "",
        ]

    for cohort_dir in sorted(p for p in results_root.iterdir() if p.is_dir()):
        cohort = cohort_dir.name
        if cohort.startswith("_"):
            continue

        lines += [f"## Cohort: {cohort}", ""]

        for relative, description in SUMMARISE.items():
            path = cohort_dir / relative
            if not path.exists():
                continue

            frame = pd.read_csv(path)
            if frame.empty:
                continue

            lines += [f"### {description}", "", f"`{relative}`", ""]
            lines.extend(render_markdown_table(frame))
            lines.append("")

    return "\n".join(lines) + "\n"


def verify(results_root: Path) -> int:
    recorded = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    by_path = {e["path"]: e for e in recorded["files"]}

    current = {e["path"]: e for e in index_results(results_root)}

    missing = sorted(set(by_path) - set(current))
    added = sorted(set(current) - set(by_path))
    changed = sorted(
        p for p in set(by_path) & set(current)
        if by_path[p]["sha256"] != current[p]["sha256"]
    )

    for label, items in (("missing", missing), ("added", added), ("changed", changed)):
        for item in items[:10]:
            print(f"  {label}: {item}")
        if len(items) > 10:
            print(f"  ... and {len(items) - 10} more {label}")

    if not (missing or added or changed):
        print(f"OK: all {len(by_path)} result files match the recorded manifest.")
        return 0

    print(
        f"\nDIFFERS from the recorded manifest: {len(missing)} missing, "
        f"{len(added)} added, {len(changed)} changed."
    )
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true",
                        help="Compare the current results against the recorded manifest.")
    args = parser.parse_args()

    results_root = ProjectPaths.project_root() / "results" / "openpowerlifting"
    if not results_root.exists():
        raise SystemExit(f"No production results at {results_root}")

    if args.verify:
        return verify(results_root)

    manifest = build_manifest(results_root)
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=4), encoding="utf-8")
    logger.info(
        "Recorded %d result files (%.1f MB) to %s",
        manifest["file_count"], manifest["total_bytes"] / 1e6, MANIFEST_PATH,
    )

    SUMMARY_PATH.write_text(render_summary(results_root), encoding="utf-8")
    logger.info("Wrote results summary to %s", SUMMARY_PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
